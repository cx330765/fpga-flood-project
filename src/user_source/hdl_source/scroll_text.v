module scroll_text #(
    parameter integer RUNTIME_SPEED_ENABLE = 0,
    parameter SCREEN_WIDTH = 640,
    parameter TEXT_Y = 432,
    parameter START_X = 640,
    parameter SPEED_DIV = 2
)(
    input wire pixel_clk, input wire reset,
    input wire [23:0] rgb_in, input wire hs_in, input wire vs_in, input wire de_in,
    input wire scroll_enable,
    input wire [1:0] speed_level,
    input wire status_panel_visible,
    output reg [23:0] rgb_out, output reg hs_out, output reg vs_out, output reg de_out
);
    localparam integer BAR_HEIGHT = 48;
    localparam integer LOGO_WIDTH = 136;
    localparam integer LOGO_HEIGHT = 40;
    localparam integer LOGO_Y_PAD = 4;
    localparam integer LOGO_GAP = 96;
    localparam integer TEXT_OFFSET = LOGO_WIDTH + LOGO_GAP;
    localparam integer TEXT_CHARS = 19;
    localparam integer CHAR_WIDTH = 32;
    localparam integer BANNER_WIDTH = TEXT_OFFSET + TEXT_CHARS * CHAR_WIDTH;

    reg [10:0] x_cnt;
    reg [9:0] y_cnt;
    reg de_d, vs_d;
    reg signed [12:0] scroll_x;
    reg [15:0] frame_counter;
    reg [1:0] speed_latched;
    wire frame_start = vs_in && !vs_d;
    wire [15:0] speed_frames = (RUNTIME_SPEED_ENABLE != 0) ?
        (speed_latched==0 ? 16'd4 : speed_latched==1 ? 16'd2 : 16'd1) : SPEED_DIV;
    always @(posedge pixel_clk or posedge reset) begin
        if(reset) speed_latched<=1;
        else if(frame_start) speed_latched<=speed_level;
    end

    wire signed [12:0] scan_x_signed = $signed({2'b00, x_cnt});
    wire signed [12:0] relative_x = scan_x_signed - scroll_x;
    wire [12:0] relative_x_u = relative_x[12:0];
    // The separately rendered status panel starts at x=504.  Reserve only
    // its actual width in normal mode, and restore the full emergency bar.
    wire [10:0] viewport_width = status_panel_visible ? 11'd504 : SCREEN_WIDTH;
    wire bar_area = scroll_enable && de_in && x_cnt < viewport_width && y_cnt >= TEXT_Y && y_cnt < TEXT_Y + BAR_HEIGHT;
    wire bar_edge = bar_area && (y_cnt == TEXT_Y || y_cnt == TEXT_Y + BAR_HEIGHT - 1);
    wire logo_area = bar_area && y_cnt >= TEXT_Y + LOGO_Y_PAD &&
        y_cnt < TEXT_Y + LOGO_Y_PAD + LOGO_HEIGHT && relative_x >= 0 && relative_x < LOGO_WIDTH;
    wire text_area = bar_area && y_cnt >= TEXT_Y + 8 && y_cnt < TEXT_Y + 40 &&
        relative_x >= TEXT_OFFSET && relative_x < BANNER_WIDTH;

    wire [9:0] text_x = relative_x_u - TEXT_OFFSET;
    wire [4:0] character_index = text_x[9:5];
    wire [3:0] font_column = text_x[4:1];
    wire [3:0] font_row = (y_cnt - (TEXT_Y + 8)) >> 1;
    reg [4:0] glyph_index;
    wire font_bit;
    wire [5:0] logo_row = y_cnt - (TEXT_Y + LOGO_Y_PAD);
    wire [7:0] logo_column = relative_x_u[7:0];
    wire [2:0] logo_color_code;

    // Fixed summary slogan: flood-shelter guidance; follow staff instructions.
    always @(*) begin
        case (character_index)
            5'd0: glyph_index = 5'd0;
            5'd1: glyph_index = 5'd1;
            5'd2: glyph_index = 5'd2;
            5'd3: glyph_index = 5'd3;
            5'd4: glyph_index = 5'd4;
            5'd5: glyph_index = 5'd5;
            5'd6: glyph_index = 5'd6;
            5'd7: glyph_index = 5'd7;
            5'd8: glyph_index = 5'd8;
            5'd9: glyph_index = 5'd31;
            5'd10: glyph_index = 5'd9;
            5'd11: glyph_index = 5'd10;
            5'd12: glyph_index = 5'd11;
            5'd13: glyph_index = 5'd12;
            5'd14: glyph_index = 5'd13;
            5'd15: glyph_index = 5'd14;
            5'd16: glyph_index = 5'd15;
            5'd17: glyph_index = 5'd2;
            5'd18: glyph_index = 5'd16;
            default: glyph_index = 5'd31;
        endcase
    end

    anlogic_full_logo_rom logo_rom(
        .row(logo_row), .column(logo_column), .color_code(logo_color_code));
    font_rom_cn_16x16 slogan_font_rom(
        .glyph_index(glyph_index), .row(font_row), .column(font_column), .font_bit(font_bit));

    always @(posedge pixel_clk or posedge reset) begin
        if (reset) begin x_cnt <= 0; y_cnt <= 0; de_d <= 0; vs_d <= 0; end
        else begin
            de_d <= de_in; vs_d <= vs_in;
            if (vs_in && !vs_d) begin x_cnt <= 0; y_cnt <= 0; end
            else begin
                if (de_in) x_cnt <= x_cnt + 1'b1; else x_cnt <= 0;
                if (de_d && !de_in) y_cnt <= y_cnt + 1'b1;
            end
        end
    end

    always @(posedge pixel_clk or posedge reset) begin
        if (reset) begin scroll_x <= 504; frame_counter <= 0; end
        else if (vs_in && !vs_d) begin
            if (scroll_enable) begin
                if (frame_counter >= speed_frames - 1) begin
                    frame_counter <= 0;
                    if (scroll_x <= -BANNER_WIDTH) scroll_x <= $signed({2'b00,viewport_width});
                    else scroll_x <= scroll_x - 13'sd1;
                end
                else frame_counter <= frame_counter + 1'b1;
            end
            else begin frame_counter <= 0; scroll_x <= $signed({2'b00,viewport_width}); end
        end
    end

    always @(posedge pixel_clk or posedge reset) begin
        if (reset) begin rgb_out <= 0; hs_out <= 0; vs_out <= 0; de_out <= 0; end
        else begin
            hs_out <= hs_in; vs_out <= vs_in; de_out <= de_in;
            if (!de_in) rgb_out <= 24'h000000;
            else if (bar_edge) rgb_out <= 24'h2080FF;
            else if (logo_area) begin
                case (logo_color_code)
                    3'd0: rgb_out <= 24'hFFFFFF;
                    3'd1: rgb_out <= 24'h001C4C;
                    3'd2: rgb_out <= 24'hEB1C24;
                    3'd3: rgb_out <= 24'h9199A5;
                    default: rgb_out <= 24'h28303E;
                endcase
            end
            else if (text_area && font_bit && character_index < 9) rgb_out <= 24'hFFE000;
            else if (text_area && font_bit) rgb_out <= 24'hFFFFFF;
            else if (bar_area) rgb_out <= 24'h001020;
            else rgb_out <= rgb_in;
        end
    end
endmodule


